Page({
  data: {
    type: 'privacy',
    title: '隐私政策',
    badge: 'PRIVACY POLICY',
    version: 'V1.2 · 2026年9月生效',
    intro: '',
    sections: [],
    readAtBottom: false
  },
  onLoad(options) {
    const type = options.type === 'service' ? 'service' : 'privacy'
    const isPrivacy = type === 'privacy'
    this.setData({
      type,
      title: isPrivacy ? '隐私政策' : '用户服务协议',
      badge: isPrivacy ? 'PRIVACY POLICY' : 'TERMS OF SERVICE',
      sections: isPrivacy ? PRIVACY_SECTIONS : SERVICE_SECTIONS,
      intro: isPrivacy
        ? '本政策说明我们如何收集、使用、存储和保护你的信息，以及你享有的权利。'
        : '本协议是你与本小程序之间关于使用音乐房间服务的约定，请在登录前仔细阅读。'
    })
    wx.setNavigationBarTitle({
      title: isPrivacy ? '隐私政策' : '用户服务协议'
    })
  },
  onPageScroll(e) {
    if (!this.data.readAtBottom && e.scrollTop > 600) {
      this.setData({ readAtBottom: true })
    }
  },
  onUnload() {
    const pages = getCurrentPages()
    const loginPage = pages.length >= 2 ? pages[pages.length - 2] : null
    if (!loginPage || !loginPage.data || loginPage.route !== 'pages/user/login') {
      return
    }
    loginPage.setData(
      this.data.type === 'privacy'
        ? { privacyRead: true }
        : { serviceRead: true }
    )
  },
  backToLogin() {
    wx.navigateBack()
  }
})
